#!/usr/bin/env python3
"""Generate css/ghost-gap-fallback.css for After Effects 2020 (Chromium 74-84).

Legacy CEF ignores flexbox/grid `gap`, so every selector that relies on it
collapses. This walks the shipped stylesheets, extracts each `gap` / `row-gap` /
`column-gap` declaration and emits an equivalent margin-based rule scoped to the
`.no-gap` capability class that js/ghost-compat.js sets at boot.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    "extension-src", "GHOST Creative System")
CSS_DIR = os.path.join(ROOT, "css")
OUT = os.path.join(CSS_DIR, "ghost-gap-fallback.css")
SKIP = {"ghost-gap-fallback.css", "ghost-legacy-compat.css",
        "ghost-ae2020-compat.css", "fontawesome-all.min.css", "ghost-tw-static.css"}

BLOCK = re.compile(r"([^{}@/]+)\{([^{}]*)\}", re.S)
GAP = re.compile(r"(?<![-\w])(gap|row-gap|column-gap)\s*:\s*([^;!}]+)", re.I)


def parse_len(token):
    token = token.strip()
    if not token or token in ("normal", "inherit", "initial", "unset"):
        return None
    if not re.match(r"^-?[\d.]+(px|rem|em)$", token):
        return None
    return token


def gaps_for(value):
    """Return (row, column) fallback lengths for a gap shorthand."""
    parts = [p for p in re.split(r"\s+", value.strip()) if p]
    if not parts:
        return None, None
    row = parse_len(parts[0])
    col = parse_len(parts[1]) if len(parts) > 1 else row
    return row, col


def main():
    out = [
        "/*! GENERATED by scripts/build-gap-fallback.py — do not edit.",
        " * Margin-based spacing for After Effects 2020/2021 (Chromium 74-84),",
        " * which ignores flexbox and grid `gap`. Scoped to .no-gap so modern",
        " * hosts keep the original layout untouched.",
        " */",
        "",
    ]
    seen = set()
    files = sorted(f for f in os.listdir(CSS_DIR)
                   if f.endswith(".css") and f not in SKIP)
    rules = 0
    for name in files:
        text = open(os.path.join(CSS_DIR, name), encoding="utf-8", errors="ignore").read()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        chunk = []
        for selector, body in BLOCK.findall(text):
            found = GAP.findall(body)
            if not found:
                continue
            row = col = None
            for prop, value in found:
                prop = prop.lower()
                if prop == "gap":
                    row, col = gaps_for(value)
                elif prop == "row-gap":
                    row = parse_len(value)
                else:
                    col = parse_len(value)
            if not row and not col:
                continue
            # A single-row flex container must not gain bottom margins, or every
            # toolbar grows taller. Vertical spacing only applies when the rule
            # itself wraps, stacks in a column, or uses grid.
            low = body.lower()
            vertical = ("column" in low or "wrap" in low
                        or re.search(r"display\s*:\s*(inline-)?grid", low) is not None
                        or "row-gap" in low)
            if not vertical:
                row = None
            if re.search(r"flex-direction\s*:\s*column", low):
                col = None
            sels = []
            for part in selector.split(","):
                part = " ".join(part.split())
                if not part or part.startswith("@") or ":" in part.split()[-1][:1]:
                    continue
                if part in (":root", "html", "*"):
                    continue
                sels.append(".no-gap " + part + " > *")
            sels = [s for s in sels if s not in seen]
            if not sels:
                continue
            seen.update(sels)
            decls = []
            if col:
                decls.append("margin-right: %s;" % col)
            if row:
                decls.append("margin-bottom: %s;" % row)
            chunk.append("%s {\n    %s\n}" % (",\n".join(sels), "\n    ".join(decls)))
            last = [s + ":last-child" for s in sels]
            reset = []
            if col:
                reset.append("margin-right: 0;")
            chunk.append("%s {\n    %s\n}" % (",\n".join(last), "\n    ".join(reset or ["margin-right: 0;"])))
            rules += 1
        if chunk:
            out.append("/* ---- %s ---- */" % name)
            out.extend(chunk)
            out.append("")
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote %s (%d gap rules from %d files)" % (os.path.relpath(OUT, ROOT), rules, len(files)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
